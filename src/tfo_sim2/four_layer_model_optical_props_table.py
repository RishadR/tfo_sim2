def get_fetal_tissue_mu_s(wavelength: float) -> float:
    """
    Get the scattering coefficient of fetal tissue at a given wavelength(nm) in mm-1 units. Based on the mimic phantoms
    paper by Husar's Group (https://ieeexplore.ieee.org/document/6943869)
    """
    cosmetic_powder_fraction = 0.1085  # Refer to Table 1 in the paper
    tio2_fraction = 0.7268  # Refer to Table 1 in the paper
    tio2_mu_s = float(interp(wavelength, tio2_mu_s_x, tio2_mu_s_y))
    cosmetic_powder_mu_s = float(interp(wavelength, cosmetic_powder_mu_s_x, cosmetic_powder_mu_s_y))
    return cosmetic_powder_fraction * cosmetic_powder_mu_s + tio2_fraction * tio2_mu_s


def get_blood_filled_tissue_mu_a(
    blood_volume_fraction: float,
    hb_concentration: float,
    saturation: float,
    wavelength: float,
    arterial_volume_fraction: Optional[float] = None,
    venous_saturation_reduction_factor: float = 0.75,
) -> float:
    """
    Generate mu_a for a blood filled tissue layer based on given parameters (in mm^-1). Meant to be used for maternal
    wall and fetal layers - Layers whose blood content is significant enough to affect the absorption coefficient.

    Args:
        blood_volume_fraction (float): Fraction of blood in the tissue layer
        hb_concentration (float): Hb Concentration Levels
        saturation (float): Blood oxygen saturation
        wavelength (float): Wavelength of the light source (in nm)

    Returns:
        float: mu_a of the tissue layer (in mm^-1)
    """
    # Base mu_a that exists even without any pigments - refer to Saidi's thesis (https://hdl.handle.net/1911/19082)
    base_tissue_mu_a = 7.84e7 * wavelength**-3.255  # in cm-1

    # Blood mu_a
    epsilon_hhb = float(interp(wavelength, epsilon_hhb_x, epsilon_hhb_y))
    epsilon_hbo2 = float(interp(wavelength, epsilon_hbo2_x, epsilon_hbo2_y))

    # Convert concentration from g/dL to Moles/liter
    # per dL -> per L : times 10; g -> M : divide by grams per Mole
    # Assume HB and HBO2 have similar molar mass
    hb_concentration = hb_concentration * 10 / 64500  # in M/L
    # Notes: molar conc. is usually around 150/64500 M/L for regular human blood

    if arterial_volume_fraction is None:
        arterial_volume_fraction = blood_volume_fraction / 2

    venous_volume_fraction = blood_volume_fraction - arterial_volume_fraction
    venous_saturation = saturation * venous_saturation_reduction_factor

    # Use mu_a formula : mu_a = 2.303 * E * Molar Concentration
    mu_a_artery = 2.303 * hb_concentration * (saturation * epsilon_hbo2 + (1 - saturation) * epsilon_hhb)  # in cm-1
    mu_a_venous = (
        2.303 * hb_concentration * (venous_saturation * epsilon_hho2 + (1 - venous_saturation) * epsilon_hhb)
    )  # in cm-1
    mu_a = venous_volume_fraction * mu_a_venous + arterial_volume_fraction * mu_a_artery + base_tissue_mu_a  # in cm-1
    mu_a = mu_a / 10  # Conversion to mm-1
    return mu_a
