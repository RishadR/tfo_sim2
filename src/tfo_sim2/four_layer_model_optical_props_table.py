def get_water_mu_s(wavelength: float) -> float:
    """
    Get the scattering coefficient of water at a given wavelength(nm) in mm-1 units. Based on the seminal paper
    "Optical properties of pure water" by Hendrik Buiteveld (1994, coincidentally the year of my birth). Check for
    total scattering cofficient, equation 4
    """
    k = 1.38064852e-23  # m^2 kg s^-2 K^-1, Boltzmann constant
    lambda_m = wavelength * 1e-9  # m
    rho = 0.051  # depolarization ratio
    T = 300  # K
    T_c = T - 273.15
    n = 1.33  # refractive index
    # This following equation is quite the mouthful. BUT this is what the paper says.
    deln_by_delp = (-0.000156 * wavelength + 1.5989) * 1e-10 * (1.61857 - 0.005785 * T_c) / (1.61857 - 0.005785 * 20)
    beta_T = (5.062271 - 0.03179 * T_c + 0.000407 * T_c**2) * 1e-11  # isotermal compressibility
    beta_90 = 2 * pi**2 * k * T / (lambda_m**4 * beta_T) * n**2 * deln_by_delp**2 * (6 + 6 * rho) / (6 - 7 * rho)
    mu_s_m = 8 * pi / 3 * beta_90 * (2 + rho) / (1 + rho)  # m^-1
    return mu_s_m * 1e-3  # mm^-1


